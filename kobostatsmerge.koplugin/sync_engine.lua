                        stats_summary.ko_to_kobo_books = stats_summary.ko_to_kobo_books + 1
                        if unified_sec > cur_ev46_sec then
                            stats_summary.ko_to_kobo_seconds = stats_summary.ko_to_kobo_seconds + (unified_sec - cur_ev46_sec)
                        end
                    end
                    local mime, book_fmt = infer_kobo_format(primary_cid, kc and kc.mime or nil)
                    local book_type = primary_cid:find("^file://") and "NotSet" or "Unlocked"

                    local orig_wc = {}
                    if grp then
                        for _, cid in ipairs(grp.cids) do
                            local e46 = events_by_cid[cid] and events_by_cid[cid][46]
                            if e46 and e46.plain and e46.plain.eventTimestamps and e46.plain.wordCounts then
                                local ets = e46.plain.eventTimestamps
                                local ewcs = e46.plain.wordCounts
                                if #ets == #ewcs then
                                    for i = 1, #ets do
                                        orig_wc[ets[i]] = ewcs[i]
                                    end
                                end
                            end
                        end
                    end

                    local merged_ts = {}
                    local merged_wc = {}
                    for i = 1, #ko_ts_list do
                        local t = ko_ts_list[i]
                        merged_ts[i] = t
                        merged_wc[i] = orig_wc[t] or 165
                    end

                    local template_ast = (cur_ev46 and cur_ev46.ast) or {}
                    local ct_node = template_ast.ContentType
                    if not ct_node then
                        ct_node = (mime == "application/x-kobo-epub+zip")
                            and QVariant.qbytearray(mime)
                            or QVariant.qstring(mime)
                    end
                    local ga4_node = template_ast.GA4 or QVariant.qstring_map({
                        book_format = book_fmt,
                        book_id = primary_cid,
                        book_type = book_type,
                    })
                    if ga4_node.value and ga4_node.value.book_id then
                        ga4_node.value.book_id = QVariant.qstring(primary_cid)
                    end
                    local dc_node = template_ast.ExtraDataDateCreated or QVariant.qstring(first_iso_z)

                    local ast_46 = {
                        ContentType = ct_node,
                        ExtraDataDateCreated = dc_node,
                        ExtraDataReadingSeconds = QVariant.qint(unified_sec),
                        ExtraDataReadingSessions = QVariant.qint(unified_sess),
                        GA4 = ga4_node,
                        PagesTurnedThisSession = QVariant.qint(0),
                        StartPercentage = QVariant.qinvalid(),
                        ViewType = QVariant.qstring("ReadingView"),
                        eventTimestamps = QVariant.qint_list(merged_ts),
                        wordCounts = QVariant.qint_list(merged_wc),
                        wordsRead = QVariant.qint(merged_wc[#merged_wc] or 165),
                    }

                    local fo_46 = (cur_ev46 and cur_ev46.fo) or first_iso
                    local lo_46 = last_iso
                    upsert_kobo_event(46, fo_46, lo_46, #merged_ts, primary_cid, ast_46)

                    local ts_3 = {}
                    for i = 1, #merged_ts do ts_3[i] = merged_ts[i] end
                    if last_ts and (ts_3[#ts_3] ~= last_ts) then
                        ts_3[#ts_3 + 1] = last_ts
                    end
                    local ast_3 = {
                        ContentType = ct_node,
                        ExtraDataDateCreated = dc_node,
                        ExtraDataReadingSeconds = QVariant.qint(unified_sec),
                        ExtraDataReadingSessions = QVariant.qint(unified_sess),
                        GA4 = ga4_node,
                        PagesTurnedThisSession = QVariant.qint(0),
                        StartPercentage = QVariant.qinvalid(),
                        ViewType = QVariant.qstring("ReadingView"),
                        eventTimestamps = QVariant.qint_list(ts_3),
                        wordCounts = QVariant.qint_list(merged_wc),
                        wordsRead = QVariant.qint(merged_wc[#merged_wc] or 165),
                    }
                    upsert_kobo_event(3, nil, lo_46, unified_sess, primary_cid, ast_3)

                    if #sess_opens > 0 then
                        upsert_kobo_event(1020, nil, ts_to_iso_ms(sess_opens[#sess_opens]), #sess_opens, primary_cid, {
                            eventTimestamps = QVariant.qint_list(sess_opens),
                        })
                        upsert_kobo_event(1021, nil, ts_to_iso_ms(sess_closes[#sess_closes]), #sess_closes, primary_cid, {
                            eventTimestamps = QVariant.qint_list(sess_closes),
                        })
                    end
                end

                -- 3. If finished (ReadStatus == 2), ensure EventType 5 and 80 exist on primary_cid
                if unified_status == 2 then
                    local ev5 = events_by_cid[primary_cid] and events_by_cid[primary_cid][5]
                    if not ev5 then
                        local fin_ts = last_ts or os.time()
                        local fin_iso = ts_to_iso_ms(fin_ts)
                        upsert_kobo_event(5, nil, fin_iso, 1, primary_cid, {
                            IsMarkAsFinished = QVariant.qbool(false),
                            eventTimestamps = QVariant.qint_list({ fin_ts }),
                        })
                    end
                    local ev80 = events_by_cid[primary_cid] and events_by_cid[primary_cid][80]
                    if not ev80 then
                        local fin_ts = last_ts or os.time()
                        local fin_iso = ts_to_iso_ms(fin_ts)
                        upsert_kobo_event(80, nil, fin_iso, 1, primary_cid, {
                            eventTimestamps = QVariant.qint_list({ fin_ts }),
                        })
                    end
                end

                -- 4. Zero out ExtraDataReadingSeconds on superseded pre-move ContentIDs in this group
                if grp then
                    for _, alt_cid in ipairs(grp.cids) do
                        if alt_cid ~= primary_cid then
                            for _, et in ipairs({ 3, 46 }) do
                                local alt_ev = events_by_cid[alt_cid] and events_by_cid[alt_cid][et]
                                if alt_ev and alt_ev.plain and (tonumber(alt_ev.plain.ExtraDataReadingSeconds) or 0) > 0 then
                                    alt_ev.ast.ExtraDataReadingSeconds = QVariant.qint(0)
                                    alt_ev.ast.ExtraDataReadingSessions = QVariant.qint(0)
                                    upsert_kobo_event(et, alt_ev.fo, alt_ev.lo, alt_ev.ec, alt_cid, alt_ev.ast)
                                end
                            end
                        end
                    end
                end

                -- 5. Record unified state in sync_state
                local new_max_ts = math.max(
                    last_ts or 0,
                    (grp and grp.max_kobo_ts) or 0,
                    (sync_state.books[book_key] and tonumber(sync_state.books[book_key].max_ts)) or 0
                )
                sync_state.books[book_key] = {
                    kobo_sec = unified_sec,
                    ko_sec = unified_sec,
                    max_ts = new_max_ts,
                }
            end
        end

        stmt_psd_book:close()
        stmt_upd_content:close()
        conn_kobo:exec("COMMIT;")
    end)

    if not ok_tx_kobo then
        pcall(conn_kobo.exec, conn_kobo, "ROLLBACK;")
        pcall(conn_ko.close, conn_ko)
        pcall(conn_kobo.close, conn_kobo)
        return false, "Transaction failed on KoboReader.sqlite: " .. tostring(err_tx_kobo)
    end

    pcall(conn_ko.exec, conn_ko, "PRAGMA wal_checkpoint(TRUNCATE);")
    pcall(conn_kobo.exec, conn_kobo, "PRAGMA wal_checkpoint(TRUNCATE);")
    conn_ko:close()
    conn_kobo:close()

    -- 5. Post-Commit Full Integrity Verification & Auto-Rollback Safety Net
    local ok_post_s, err_post_s = SyncEngine.check_db_integrity(stats_db, true)
    if not ok_post_s then
        SyncEngine.restore_from_backup(backup_dir, "statistics.sqlite3", stats_db, false)
        return false, "Post-sync integrity check failed on statistics.sqlite3 (auto-restored backup): " .. tostring(err_post_s)
    end
    local ok_post_k, err_post_k = SyncEngine.check_db_integrity(kobo_db, true)
    if not ok_post_k then
        SyncEngine.restore_from_backup(backup_dir, "KoboReader.sqlite", kobo_db, false)
        return false, "Post-sync integrity check failed on KoboReader.sqlite (auto-restored backup): " .. tostring(err_post_k)
    end

    save_sync_state(state_path, sync_state)
    return true, stats_summary
end

return SyncEngine
