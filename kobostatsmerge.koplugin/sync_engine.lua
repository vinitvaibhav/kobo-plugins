-- sync_engine.lua
-- Bidirectional (2-Way) Reading Statistics Synchronization Engine
-- between Kobo Stock App (.kobo/KoboReader.sqlite) and KOReader (statistics.sqlite3).

local SQ3 = require("lua-ljsqlite3/init")
local QVariant = require("qvariant")

local SyncEngine = {}

-- Default configuration paths on Kobo device
SyncEngine.DEFAULT_KOBO_DB = "/mnt/onboard/.kobo/KoboReader.sqlite"
SyncEngine.DEFAULT_ONBOARD_DIR = "/mnt/onboard"
SyncEngine.MAX_BACKUP_GENERATIONS = 3

-- Format UNIX timestamp to Kobo ISO8601 UTC strings
local function ts_to_iso_ms(ts)
    ts = math.floor(tonumber(ts) or os.time())
    return os.date("!%Y-%m-%dT%H:%M:%S.000", ts)
end

local function ts_to_iso_z(ts)
    ts = math.floor(tonumber(ts) or os.time())
    return os.date("!%Y-%m-%dT%H:%M:%SZ", ts)
end

-- Parse Kobo ISO8601 UTC string ("YYYY-MM-DDTHH:MM:SS.000" or "Z") to epoch seconds
local function iso_to_ts(iso_str)
    if type(iso_str) ~= "string" or iso_str == "" then return nil end
    local y, m, d, H, M, S = iso_str:match("^(%d%d%d%d)%-(%d%d)%-(%d%d)T(%d%d):(%d%d):(%d%d)")
    if not y then return nil end
    local yr = tonumber(y)
    if not yr or yr < 1971 then return nil end
    local now = os.time()
    local utc_now = os.time(os.date("!*t", now))
    local tz_offset = os.difftime(now, utc_now)
    local local_t = os.time({
        year = yr, month = tonumber(m), day = tonumber(d),
        hour = tonumber(H), min = tonumber(M), sec = tonumber(S),
        isdst = false,
    })
    return local_t and math.floor(local_t + tz_offset) or nil
end

-- Normalize book title or filename stem for cross-app matching
function SyncEngine.normalize_title(s)
    if type(s) ~= "string" or s == "" then return "" end
    local t = s:lower()
    t = t:gsub("^file://", "")
    t = t:gsub("^.+/", "")
    t = t:gsub("%.kepub%.epub$", "")
    t = t:gsub("%.epub$", "")
    t = t:gsub("%.pdf$", "")
    t = t:gsub("%.cbz$", "")
    t = t:gsub("%.cbr$", "")
    t = t:gsub("%.mobi$", "")
    t = t:gsub("%.txt$", "")
    t = t:gsub("%.html?$", "")
    t = t:gsub("%.rtf$", "")
    -- Strip date/timestamp prefixes like "26-08-31_15-06_" or "2026-08-31_"
    t = t:gsub("^%d%d+[%-_]%d+[%-_]%d+[_%-%s]*%d*[%-_:]?%d*[_%-%s]*", "")
    t = t:gsub("_", " ")
    t = t:gsub("^.-#%d+%s*%-+%s*", "")
    t = t:gsub("%s+by%s+.+$", "")
    local core = t:gsub("%s*%b()%s*", " ")
    core = core:gsub("%s+[%-%:—–]%s+.+$", "")
    core = core:gsub("[^%w%s]", " "):gsub("%s+", " "):match("^%s*(.-)%s*$")
    t = t:gsub("[^%w%s]", " "):gsub("%s+", " "):match("^%s*(.-)%s*$")
    return t, (core ~= "" and core or t)
end

-- Determine Kobo MimeType and GA4 book_format from path / ContentID
local function infer_kobo_format(cid_or_path, existing_mime)
    if existing_mime and existing_mime ~= "" then
        local fmt = "EPUB"
        if existing_mime:find("kobo%-epub") then fmt = "KOBO_EPUB"
        elseif existing_mime:find("pdf") then fmt = "PDF"
        elseif existing_mime:find("cbz") then fmt = "CBZ"
        elseif existing_mime:find("cbr") then fmt = "CBR"
        end
        return existing_mime, fmt
    end
    local lower = (cid_or_path or ""):lower()
    if lower:find("%.kepub%.epub$") or not lower:find("^file://") then
        return "application/x-kobo-epub+zip", "KOBO_EPUB"
    elseif lower:find("%.pdf$") then
        return "application/pdf", "PDF"
    elseif lower:find("%.cbz$") then
        return "application/x-cbz", "CBZ"
    elseif lower:find("%.cbr$") then
        return "application/x-cbr", "CBR"
    elseif lower:find("%.txt$") then
        return "text/plain", "TXT"
    elseif lower:find("%.html?$") then
        return "text/html", "HTML"
    elseif lower:find("%.mobi$") then
        return "application/x-mobipocket-ebook", "MOBI"
    else
        return "application/epub+zip", "EPUB"
    end
end

-- Persistent sync state loader & saver
local function load_sync_state(state_path)
    if not state_path then return { books = {} } end
    local f = io.open(state_path, "r")
    if not f then return { books = {} } end
    f:close()
    local ok, data = pcall(dofile, state_path)
    if ok and type(data) == "table" and type(data.books) == "table" then
        return data
    end
    return { books = {} }
end

local function save_sync_state(state_path, state)
    if not state_path or type(state) ~= "table" then return false end
    local tmp = state_path .. ".tmp"
    local f = io.open(tmp, "w")
    if not f then return false end
    f:write("-- Auto-generated by kobostatsmerge.koplugin\nreturn {\n  last_sync = ")
    f:write(tostring(os.time()))
    f:write(",\n  books = {\n")
    local keys = {}
    for k, _ in pairs(state.books or {}) do keys[#keys + 1] = k end
    table.sort(keys)
    for _, k in ipairs(keys) do
        local v = state.books[k]
        f:write(string.format(
            "    [%q] = { kobo_sec = %d, ko_sec = %d, max_ts = %d },\n",
            k,
            tonumber(v.kobo_sec) or 0,
            tonumber(v.ko_sec) or 0,
            tonumber(v.max_ts) or 0
        ))
    end
    f:write("  },\n}\n")
    f:flush()
    f:close()
    os.remove(state_path)
    os.rename(tmp, state_path)
    return true
end

-- Binary-safe file copy with size check and atomic temp rename
function SyncEngine.copy_file(src, dst)
    local rf, err_r = io.open(src, "rb")
    if not rf then return false, "Cannot open source: " .. tostring(err_r) end
    local tmp_dst = dst .. ".tmp"
    local wf, err_w = io.open(tmp_dst, "wb")
    if not wf then
        rf:close()
        return false, "Cannot open temp destination: " .. tostring(err_w)
    end
    local total_bytes = 0
    while true do
        local chunk = rf:read(65536)
        if not chunk then break end
        local ok_w, w_err = wf:write(chunk)
        if not ok_w then
            rf:close()
            wf:close()
            os.remove(tmp_dst)
            return false, "Write error: " .. tostring(w_err)
        end
        total_bytes = total_bytes + #chunk
    end
    rf:close()
    wf:flush()
    wf:close()

    local vf = io.open(tmp_dst, "rb")
    if not vf then
        os.remove(tmp_dst)
        return false, "Verification open failed"
    end
    local v_size = vf:seek("end")
    vf:close()
    if v_size ~= total_bytes or total_bytes == 0 then
        os.remove(tmp_dst)
        return false, string.format("Size mismatch (%s != %s)", tostring(v_size), tostring(total_bytes))
    end
    os.remove(dst)
    local ok_ren, ren_err = os.rename(tmp_dst, dst)
    if not ok_ren then
        os.remove(tmp_dst)
        return false, "Rename failed: " .. tostring(ren_err)
    end
    return true, total_bytes
end

-- Check SQLite database integrity ("quick_check" or full "integrity_check")
function SyncEngine.check_db_integrity(db_path, full_check)
    local f = io.open(db_path, "rb")
    if not f then return false, "Database file does not exist: " .. tostring(db_path) end
    f:close()
    local ok_open, conn = pcall(SQ3.open, db_path)
    if not ok_open or not conn then
        return false, "SQ3.open failed: " .. tostring(conn)
    end
    pcall(conn.set_busy_timeout, conn, 3000)
    local pragma_sql = full_check and "PRAGMA integrity_check;" or "PRAGMA quick_check;"
    local ok_q, res = pcall(conn.rowexec, conn, pragma_sql)
    local ok_fk = true
    if full_check and ok_q and res == "ok" then
        local ok_f, fk_res = pcall(conn.rowexec, conn, "PRAGMA foreign_key_check;")
        if ok_f and fk_res ~= nil then
            ok_fk = false
            res = "foreign_key_check failed"
        end
    end
    pcall(conn.close, conn)
    if not ok_q or res ~= "ok" or not ok_fk then
        return false, "Integrity check failed on " .. tostring(db_path) .. ": " .. tostring(res)
    end
    return true, "ok"
end

-- Ensure backup directory exists
local function ensure_dir(dir)
    if not dir or dir == "" then return end
    local ok_lfs, lfs = pcall(require, "libs/libkoreader-lfs")
    if ok_lfs and lfs and lfs.attributes(dir, "mode") == "directory" then return end
    os.execute("mkdir -p " .. string.format("%q", dir))
end

-- Create rolling backups (.bak.1, .bak.2, .bak.3) and an untouched .golden.bak
function SyncEngine.create_rolling_backup(db_path, backup_dir, prefix)
    ensure_dir(backup_dir)
    local ok_int, err_int = SyncEngine.check_db_integrity(db_path, false)
    if not ok_int then
        return false, "Refusing to back up unhealthy DB: " .. tostring(err_int)
    end
    local golden = backup_dir .. "/" .. prefix .. ".golden.bak"
    local gf = io.open(golden, "rb")
    if gf then
        gf:close()
    else
        local ok_g, err_g = SyncEngine.copy_file(db_path, golden)
        if not ok_g then return false, "Golden backup failed: " .. tostring(err_g) end
    end

    for i = SyncEngine.MAX_BACKUP_GENERATIONS - 1, 1, -1 do
        local src = string.format("%s/%s.bak.%d", backup_dir, prefix, i)
        local dst = string.format("%s/%s.bak.%d", backup_dir, prefix, i + 1)
        local sf = io.open(src, "rb")
        if sf then
            sf:close()
            os.remove(dst)
            os.rename(src, dst)
        end
    end
    local bak1 = string.format("%s/%s.bak.1", backup_dir, prefix)
    local ok_b, err_b = SyncEngine.copy_file(db_path, bak1)
    if not ok_b then return false, "Rolling backup .bak.1 failed: " .. tostring(err_b) end
    return true, bak1
end

-- Restore database from .bak.1 or .golden.bak
function SyncEngine.restore_from_backup(backup_dir, prefix, target_db_path, use_golden)
    local src = use_golden
        and (backup_dir .. "/" .. prefix .. ".golden.bak")
        or (backup_dir .. "/" .. prefix .. ".bak.1")
    local ok_int, err_int = SyncEngine.check_db_integrity(src, true)
    if not ok_int then
        return false, "Backup file integrity check failed: " .. tostring(err_int)
    end
    local ok_cp, err_cp = SyncEngine.copy_file(src, target_db_path)
    if not ok_cp then
        return false, "Restore copy failed: " .. tostring(err_cp)
    end
    return SyncEngine.check_db_integrity(target_db_path, true)
end

-- Extract chronological reading intervals (start_time, duration) from Kobo Event 1020, 1021, 46
-- Only extracts intervals strictly after min_after_ts (if > 0)
local function extract_kobo_intervals(events_by_cid, cids, target_delta_sec, first_iso, last_iso, min_after_ts)
    min_after_ts = tonumber(min_after_ts) or 0
    local raw_views = {}
    local max_seen_ts = min_after_ts
    local min_dur, max_chunk, max_interval_cap = 5, 120, 420

    for _, cid in ipairs(cids) do
        local ev = events_by_cid[cid] or {}
        local t46 = {}
        local t1020 = {}
        local t1021 = {}
        for _, v in ipairs((ev[46] and ev[46].plain and ev[46].plain.eventTimestamps) or {}) do
            t46[#t46 + 1] = v
            if v > max_seen_ts then max_seen_ts = v end
        end
        for _, v in ipairs((ev[1020] and ev[1020].plain and ev[1020].plain.eventTimestamps) or {}) do
            t1020[#t1020 + 1] = v
            if v > max_seen_ts then max_seen_ts = v end
        end
        for _, v in ipairs((ev[1021] and ev[1021].plain and ev[1021].plain.eventTimestamps) or {}) do
            t1021[#t1021 + 1] = v
            if v > max_seen_ts then max_seen_ts = v end
        end
        table.sort(t46)
        table.sort(t1020)
        table.sort(t1021)

        local cid_sessions = {}
        local j = 1
        for i = 1, #t1020 do
            local s_start = t1020[i]
            local next_start = t1020[i + 1] or math.huge
            while j <= #t1021 and t1021[j] < s_start do
                j = j + 1
            end
            if j <= #t1021 and t1021[j] <= next_start then
                if t1021[j] > min_after_ts then
                    cid_sessions[#cid_sessions + 1] = { math.max(s_start, min_after_ts), t1021[j] }
                end
                j = j + 1
            end
        end

        for _, sb in ipairs(cid_sessions) do
            local s_start, s_end = sb[1], sb[2]
            local bounds = { s_start }
            for _, pt in ipairs(t46) do
                if pt > s_start and pt < s_end then
                    bounds[#bounds + 1] = pt
                end
            end
            bounds[#bounds + 1] = s_end
            for k = 1, #bounds - 1 do
                local a, b = bounds[k], bounds[k + 1]
                local d = b - a
                if d >= min_dur then
                    local rem = math.min(d, max_interval_cap)
                    local cur_t = a
                    while rem >= min_dur do
                        local chunk = math.min(rem, max_chunk)
                        if (rem - chunk) > 0 and (rem - chunk) < min_dur then
                            chunk = rem - min_dur
                            if chunk < min_dur then
                                chunk = math.min(rem, max_chunk)
                                raw_views[#raw_views + 1] = { cur_t, chunk }
                                break
                            end
                        end
                        raw_views[#raw_views + 1] = { cur_t, chunk }
                        cur_t = cur_t + chunk
                        rem = rem - chunk
                    end
                end
            end
        end
    end

    table.sort(raw_views, function(a, b) return a[1] < b[1] end)
    local deduped = {}
    local seen_ts = {}
    local sum_sec = 0
    for i = 1, #raw_views do
        local ts, dur = raw_views[i][1], raw_views[i][2]
        while seen_ts[ts] do ts = ts + 1 end
        seen_ts[ts] = true
        deduped[#deduped + 1] = { ts, dur }
        sum_sec = sum_sec + dur
    end

    -- Fallback if Kobo recorded reading seconds without 1020/1021 timestamps (e.g. PDF or preview)
    if #deduped == 0 and target_delta_sec and target_delta_sec > 0 then
        local last_ts_val = iso_to_ts(last_iso) or iso_to_ts(first_iso) or os.time()
        local start_ts = math.max(min_after_ts + 1, last_ts_val - target_delta_sec)
        local cur_t = start_ts
        local rem = target_delta_sec
        while rem > 0 do
            local ch = math.min(rem, max_chunk)
            while seen_ts[cur_t] do cur_t = cur_t + 1 end
            seen_ts[cur_t] = true
            deduped[#deduped + 1] = { cur_t, ch }
            if cur_t + ch > max_seen_ts then max_seen_ts = cur_t + ch end
            cur_t = cur_t + ch
            rem = rem - ch
            sum_sec = sum_sec + ch
        end
    end

    return deduped, sum_sec, max_seen_ts
end

-- Parse .sdr sidecar Lua file lightly to extract summary.status, percent_finished, partial_md5_checksum
local function parse_sdr_sidecar(book_path)
    if type(book_path) ~= "string" or book_path == "" then return nil end
    local dir, fname = book_path:match("^(.-)([^/]+)$")
    if not fname then return nil end
    local stem, ext = fname:match("^(.+)%.([^%.]+)$")
    if not stem then return nil end
    local sdr_meta = string.format("%s%s.sdr/metadata.%s.lua", dir, stem, ext:lower())
    local f = io.open(sdr_meta, "r")
    if not f then return nil end
    local content = f:read("*a")
    f:close()
    if not content then return nil end
    local status = content:match('%["status"%]%s*=%s*"([^"]+)"')
    local pct = tonumber(content:match('%["percent_finished"%]%s*=%s*([%d%.]+)'))
    local md5 = content:match('%["partial_md5_checksum"%]%s*=%s*"([^"]+)"')
    return {
        status = status,
        percent_finished = pct,
        md5 = md5,
        sdr_path = sdr_meta,
    }
end

local function resolve_local_path(kobo_path, onboard_dir)
    if type(kobo_path) ~= "string" then return nil end
    local p = kobo_path:gsub("^file://", "")
    if onboard_dir and onboard_dir ~= "/mnt/onboard" then
        p = p:gsub("^/mnt/onboard", onboard_dir)
    end
    return p
end

-- Main 2-Way Synchronization Entrypoint
function SyncEngine.run_two_way_sync(opts)
    opts = opts or {}
    local kobo_db = opts.kobo_db_path or SyncEngine.DEFAULT_KOBO_DB
    local stats_db = opts.stats_db_path
    local bookinfo_db = opts.bookinfo_db_path
    local history_path = opts.history_path
    local backup_dir = opts.backup_dir
    local state_path = opts.state_path or (backup_dir and (backup_dir .. "/kobo_stats_sync_state.lua") or nil)
    local onboard_dir = opts.onboard_dir or SyncEngine.DEFAULT_ONBOARD_DIR

    if not stats_db or not backup_dir then
        return false, "Missing required stats_db_path or backup_dir"
    end

    -- 1. Pre-flight Integrity Gate
    local ok_s, err_s = SyncEngine.check_db_integrity(stats_db, false)
    if not ok_s then return false, "Pre-flight failed on statistics.sqlite3: " .. tostring(err_s) end
    local ok_k, err_k = SyncEngine.check_db_integrity(kobo_db, false)
    if not ok_k then return false, "Pre-flight failed on KoboReader.sqlite: " .. tostring(err_k) end

    -- 2. Rolling Backups Gate
    local ok_bs, err_bs = SyncEngine.create_rolling_backup(stats_db, backup_dir, "statistics.sqlite3")
    if not ok_bs then return false, "Backup failed for statistics.sqlite3: " .. tostring(err_bs) end
    local ok_bk, err_bk = SyncEngine.create_rolling_backup(kobo_db, backup_dir, "KoboReader.sqlite")
    if not ok_bk then return false, "Backup failed for KoboReader.sqlite: " .. tostring(err_bk) end

    local sync_state = load_sync_state(state_path)

    -- 3. Load known book paths & metadata from bookinfo_cache.sqlite3 and history.lua
    local path_by_title = {}
    local title_by_path = {}
    local sdr_by_title = {}
    local function register_known_file(kobo_file_path, title_hint)
        if not kobo_file_path then return end
        local bare_p = kobo_file_path:gsub("^file://", "")
        if title_hint and title_hint ~= "" then
            title_by_path[kobo_file_path] = title_hint
            title_by_path["file://" .. bare_p] = title_hint
            title_by_path[bare_p] = title_hint
        end
        local local_p = resolve_local_path(kobo_file_path, onboard_dir)
        local sdr = parse_sdr_sidecar(local_p)
        local norm_f, core_f = SyncEngine.normalize_title(kobo_file_path)
        if norm_f ~= "" then
            path_by_title[norm_f] = path_by_title[norm_f] or kobo_file_path
            path_by_title[core_f] = path_by_title[core_f] or kobo_file_path
            if sdr then
                sdr_by_title[norm_f] = sdr
                sdr_by_title[core_f] = sdr
            end
        end
        if title_hint and title_hint ~= "" then
            local nt, ct = SyncEngine.normalize_title(title_hint)
            if nt ~= "" then
                path_by_title[nt] = path_by_title[nt] or kobo_file_path
                path_by_title[ct] = path_by_title[ct] or kobo_file_path
                if sdr then
                    sdr_by_title[nt] = sdr
                    sdr_by_title[ct] = sdr
                end
            end
        end
    end

    if bookinfo_db then
        local f_bi = io.open(bookinfo_db, "rb")
        if f_bi then
            f_bi:close()
            local ok_b, conn_bi = pcall(SQ3.open, bookinfo_db)
            if ok_b and conn_bi then
                pcall(function()
                    local stmt = conn_bi:prepare("SELECT directory, filename, title FROM bookinfo WHERE filename IS NOT NULL;")
                    for row in stmt:rows() do
                        local dir, fn, t = tostring(row[1] or ""), tostring(row[2] or ""), row[3] and tostring(row[3]) or nil
                        register_known_file(dir .. fn, t)
                    end
                    stmt:close()
                end)
                pcall(conn_bi.close, conn_bi)
            end
        end
    end

    if history_path then
        local ok_h, hist = pcall(dofile, history_path)
        if ok_h and type(hist) == "table" then
            for _, entry in ipairs(hist) do
                if type(entry) == "table" and type(entry.file) == "string" then
                    register_known_file(entry.file, nil)
                end
            end
        end
    end

    -- 4. Open both databases
    local conn_ko = SQ3.open(stats_db)
    conn_ko:set_busy_timeout(3000)
    local conn_kobo = SQ3.open(kobo_db)
    conn_kobo:set_busy_timeout(3000)

    -- Read Kobo content rows (ContentType = '6')
    local kobo_content = {}
    local stmt_kc = conn_kobo:prepare([[
        SELECT ContentID, MimeType, Title, Attribution, ReadStatus, ___PercentRead,
               TimeSpentReading, TimesStartedReading, FirstTimeReading, DateLastRead,
               LastTimeStartedReading, LastTimeFinishedReading, RestOfBookEstimate,
               Series, SeriesNumber, Language
        FROM content
        WHERE ContentType = '6';
    ]])
    for row in stmt_kc:rows() do
        local cid = tostring(row[1])
        local title = row[3] and tostring(row[3]) or ""
        if not cid:find("^file://") and title ~= "" then
            local nt, ct = SyncEngine.normalize_title(title)
            if path_by_title[nt] then
                register_known_file(path_by_title[nt], title)
            end
        else
            register_known_file(cid:gsub("^file://", ""), title)
        end
        kobo_content[cid] = {
            cid = cid,
            mime = row[2] and tostring(row[2]) or "application/x-kobo-epub+zip",
            title = title,
            authors = row[4] and tostring(row[4]) or "N/A",
            read_status = tonumber(row[5]) or 0,
            percent_read = tonumber(row[6]) or 0,
            time_spent = tonumber(row[7]) or 0,
            times_started = tonumber(row[8]) or 0,
            first_time = row[9] and tostring(row[9]) or "true",
            date_last_read = row[10] and tostring(row[10]) or nil,
            last_started = row[11] and tostring(row[11]) or nil,
            last_finished = row[12] and tostring(row[12]) or nil,
            rest_estimate = tonumber(row[13]) or 0,
            series = row[14] and tostring(row[14]) or nil,
            series_num = row[15] and tostring(row[15]) or nil,
            language = row[16] and tostring(row[16]) or "en",
        }
    end
    stmt_kc:close()

    -- Read Kobo Event rows (3, 46, 5, 80, 1020, 1021)
    local events_by_cid = {}
    local stmt_ev = conn_kobo:prepare([[
        SELECT EventType, FirstOccurrence, LastOccurrence, EventCount, ContentID, hex(ExtraData), Checksum
        FROM Event
        WHERE EventType IN (3, 46, 5, 80, 1020, 1021);
    ]])
    for row in stmt_ev:rows() do
